"""Import open-licensed piece sets into packages/ui (ТЗ §12: check every set's licence).

Run: python3 tools/pieces/import.py
Source: lichess-org/lila public/piece/<set> (licences per lila COPYING.md).
The app is GPL-3.0-or-later, so GPL sets are allowed. AGPL and non-commercial (NC)
sets (alpha, staunty, maestro, …) are excluded.
"""
import json
import os
import re
import urllib.request

SETS = {
    'cburnett': ('Cburnett', 'Colin M.L. Burnett', 'GPL-2.0-or-later', 'https://en.wikipedia.org/wiki/User:Cburnett'),
    'merida': ('Merida', 'Armando Hernandez Marroquin', 'GPL-2.0-or-later', 'https://github.com/lichess-org/lila'),
    'mpchess': ('MPChess', 'Maxime Chupin', 'GPL-3.0-or-later', 'https://github.com/chupinmaxime'),
    'chessnut': ('Chessnut', 'Alexis Luengas', 'Apache-2.0', 'https://github.com/LexLuengas/chessnut-pieces'),
    'celtic': ('Celtic', 'Maurizio Monge', 'MIT', 'https://github.com/maurimo/chess-art'),
    'spatial': ('Spatial', 'Maurizio Monge', 'MIT', 'https://github.com/maurimo/chess-art'),
    'papercut': ('Papercut', 'Nikolay Anzarov', 'CC-BY-4.0', 'https://nikoichu.itch.io/'),
}
PIECES = ['wK', 'wQ', 'wR', 'wB', 'wN', 'wP', 'bK', 'bQ', 'bR', 'bB', 'bN', 'bP']
BASE = 'https://raw.githubusercontent.com/lichess-org/lila/master/public/piece'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'packages', 'ui', 'src', 'board', 'pieceSets')


def minify(svg: str) -> str:
    svg = re.sub(r'<\?xml.*?\?>', '', svg, flags=re.S)
    svg = re.sub(r'<!DOCTYPE.*?>', '', svg, flags=re.S)
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'<metadata.*?</metadata>', '', svg, flags=re.S)
    svg = re.sub(r'<sodipodi:namedview.*?(/>|</sodipodi:namedview>)', '', svg, flags=re.S)
    svg = re.sub(r'\s(?:sodipodi|inkscape):[\w-]+="[^"]*"', '', svg)
    svg = re.sub(r'>\s+<', '><', svg)
    svg = re.sub(r'\s+', ' ', svg)
    return svg.strip()


def main():
    os.makedirs(OUT, exist_ok=True)
    index = []
    for set_id, (name, author, licence, url) in SETS.items():
        pieces = {}
        for p in PIECES:
            with urllib.request.urlopen(f'{BASE}/{set_id}/{p}.svg', timeout=30) as r:
                pieces[p] = minify(r.read().decode('utf-8'))
        var = re.sub(r'\W', '_', set_id)
        body = ',\n'.join(f'  {p}: {json.dumps(s, ensure_ascii=False)}' for p, s in pieces.items())
        with open(os.path.join(OUT, f'{set_id}.ts'), 'w') as f:
            f.write(
                f'// Generated by tools/pieces/import.py — do not edit.\n'
                f'// «{name}» by {author}, licence {licence} ({url}).\n'
                f'import type {{ PieceSvgs }} from \'./types\';\n\n'
                f'export const {var}: PieceSvgs = {{\n{body},\n}};\n'
            )
        index.append((set_id, var, name, author, licence, url))
        print(f'{set_id}: {sum(len(s) for s in pieces.values()) // 1024} KB')

    with open(os.path.join(OUT, 'index.ts'), 'w') as f:
        f.write('// Generated by tools/pieces/import.py — do not edit.\n')
        f.write("import type { PieceSet } from './types';\n")
        for set_id, var, *_ in index:
            f.write(f"import {{ {var} }} from './{set_id}';\n")
        f.write('\nexport const pieceSets = {\n')
        for set_id, var, name, author, licence, url in index:
            f.write(
                f"  {json.dumps(set_id)}: {{ id: {json.dumps(set_id)}, name: {json.dumps(name)}, "
                f"author: {json.dumps(author)}, license: {json.dumps(licence)}, url: {json.dumps(url)}, svgs: {var} }},\n"
            )
        f.write('} as const satisfies Record<string, PieceSet>;\n\n')
        f.write('export type PieceSetId = keyof typeof pieceSets;\n')
        f.write('export const PIECE_SET_IDS = Object.keys(pieceSets) as PieceSetId[];\n')
        f.write(f"export const DEFAULT_PIECE_SET: PieceSetId = {json.dumps(index[0][0])};\n")
        f.write("export type { PieceCode, PieceSet, PieceSvgs } from './types';\n")


if __name__ == '__main__':
    main()
